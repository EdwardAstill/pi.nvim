local function real_index_tree(root)
  return H.git(root, { "write-tree" })
end

local function assert_real_index(root, expected, operation)
  H.eq(expected, real_index_tree(root), operation .. " must not change the real index")
end

local function write_bytes(path, data, mode)
  vim.fn.mkdir(vim.fn.fnamemodify(path, ":h"), "p")
  local fd = assert(vim.uv.fs_open(path, "w", mode or 420))
  assert(vim.uv.fs_write(fd, data, 0))
  assert(vim.uv.fs_close(fd))
end

H.test("changed_files, diff, and hunk_count report literal tree differences", function()
  local Git = require("pi.review.git")
  local root = H.repo()
  local git = assert(Git.new(root))
  local first = assert(git:snapshot())
  local real_index_before = real_index_tree(root)
  H.write(root .. "/tracked.txt", "changed\n")
  H.write(root .. "/new file.txt", "new\n")
  local second = assert(git:snapshot())
  local files = assert(git:changed_files(first, second))
  H.eq({
    { path = "new file.txt", status = "A", additions = 1, deletions = 0, binary = false },
    { path = "tracked.txt", status = "M", additions = 1, deletions = 1, binary = false },
  }, files)
  assert_real_index(root, real_index_before, "changed_files")
  local patch = assert(git:diff(first, second, "tracked.txt"))
  H.truthy(patch:find("-base\n+changed\n", 1, true), "diff must contain the literal changed lines")
  assert_real_index(root, real_index_before, "diff")
  H.eq(1, assert(git:hunk_count(first, second, "tracked.txt")))
  assert_real_index(root, real_index_before, "hunk_count")
  git:cleanup()
end)

H.test("changed_files reports binary numstat fields", function()
  local Git = require("pi.review.git")
