H.test("entry and read_file preserve executable mode and exact bytes", function()
  local Git = require("pi.review.git")
  local root = H.repo()
  H.write(root .. "/script.sh", "#!/bin/sh\nprintf exact\n")
  assert(vim.uv.fs_chmod(root .. "/script.sh", 493))
  local git = assert(Git.new(root))
  local tree = assert(git:snapshot())
  local real_index_before = real_index_tree(root)
  local entry = assert(git:entry(tree, "script.sh"))
  H.eq("100755", entry.mode)
  H.eq("blob", entry.type)
  H.eq("script.sh", entry.path)
  H.truthy(entry.oid:match("^[0-9a-f]+$") and #entry.oid == 40)
  assert_real_index(root, real_index_before, "entry")
  local file = assert(git:read_file(tree, "script.sh"))
  H.eq("#!/bin/sh\nprintf exact\n", file.data)
  H.eq("100755", file.mode)
  H.eq(entry.oid, file.oid)
  assert_real_index(root, real_index_before, "read_file")
  git:cleanup()
end)

H.test("copy_path changes only the selected path in a tree", function()
  local Git = require("pi.review.git")
  local root = H.repo()
  H.write(root .. "/other.txt", "other-base\n")
