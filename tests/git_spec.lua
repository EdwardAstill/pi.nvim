  assert_real_index(root, real_index_before, "update_path addition")
  git:cleanup()
end)

H.test("restore_path restores bytes and mode and removes a path absent from the tree", function()
  local Git = require("pi.review.git")
  local root = H.repo()
  H.write(root .. "/script.sh", "#!/bin/sh\nprintf restored\n")
  assert(vim.uv.fs_chmod(root .. "/script.sh", 493))
  local git = assert(Git.new(root))
  local accepted = assert(git:snapshot())
  local real_index_before = real_index_tree(root)
  H.write(root .. "/script.sh", "changed\n")
  assert(vim.uv.fs_chmod(root .. "/script.sh", 420))
  H.write(root .. "/new.txt", "remove me\n")
  H.eq(true, assert(git:restore_path(accepted, "script.sh")))
  H.eq("#!/bin/sh\nprintf restored\n", H.read(root .. "/script.sh"))
  H.eq(493, bit.band(assert(vim.uv.fs_stat(root .. "/script.sh")).mode, 511))
  assert_real_index(root, real_index_before, "restore_path regular file")
  local restored_again = git:restore_path(accepted, "new.txt")
  H.eq(true, restored_again)
  H.eq(nil, vim.uv.fs_lstat(root .. "/new.txt"))
  assert_real_index(root, real_index_before, "restore_path absent file")
  local absent_again = git:restore_path(accepted, "new.txt")
  H.eq(true, absent_again)
  assert_real_index(root, real_index_before, "restore_path already-absent file")
  git:cleanup()
end)

H.test("restore_path recreates a symbolic link from exact blob bytes", function()
  local Git = require("pi.review.git")
  local root = H.repo()
  assert(vim.uv.fs_symlink("tracked.txt", root .. "/link"))
  local git = assert(Git.new(root))
  local accepted = assert(git:snapshot())
  local real_index_before = real_index_tree(root)
  assert(vim.uv.fs_unlink(root .. "/link"))
  H.write(root .. "/link", "ordinary file\n")
  H.eq(true, assert(git:restore_path(accepted, "link")))
  H.eq("link", assert(vim.uv.fs_lstat(root .. "/link")).type)
  H.eq("tracked.txt", assert(vim.uv.fs_readlink(root .. "/link")))
  assert_real_index(root, real_index_before, "restore_path symlink")
  git:cleanup()
end)

H.test("restore_path checks out a Gitlink only in a clean initialized submodule", function()
  local Git = require("pi.review.git")
  local child = H.repo()
  local accepted_oid = H.git(child, { "rev-parse", "HEAD" })
  local root = H.repo()
  H.git(root, { "-c", "protocol.file.allow=always", "submodule", "add", "-q", child, "module" })
  H.git(root, { "commit", "-qam", "add submodule" })
  local git = assert(Git.new(root))
  local accepted = assert(git:snapshot())
  H.write(child .. "/tracked.txt", "new child commit\n")
  H.git(child, { "commit", "-qam", "second" })
  local current_oid = H.git(child, { "rev-parse", "HEAD" })
  H.git(root .. "/module", { "fetch", "-q", "origin" })
  H.git(root .. "/module", { "checkout", "-q", "--detach", current_oid })
  H.git(root, { "add", "module" })
  local real_index_before = real_index_tree(root)
  H.eq(true, assert(git:restore_path(accepted, "module")))
  H.eq(accepted_oid, H.git(root .. "/module", { "rev-parse", "HEAD" }))
  assert_real_index(root, real_index_before, "restore_path Gitlink")

  H.write(root .. "/module/tracked.txt", "dirty\n")
  local ok, err = git:restore_path(assert(git:snapshot()), "module")
  H.eq(nil, ok)
  H.eq("git", err.kind)
  H.truthy(err.message:find("clean", 1, true))
  H.eq("dirty\n", H.read(root .. "/module/tracked.txt"))
  assert_real_index(root, real_index_before, "refused dirty Gitlink restore")
  git:cleanup()
end)

