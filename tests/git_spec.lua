H.test("restore_path rejects a sibling-prefix escape without disk or index mutation", function()
  local Git = require("pi.review.git")
  local parent = H.tmpdir()
  local root = parent .. "/repository"
  local sibling = parent .. "/repository-evil"
  vim.fn.mkdir(root, "p")
  vim.fn.mkdir(sibling, "p")
  H.git(root, { "init", "-q" })
  H.git(root, { "config", "user.name", "pi.nvim tests" })
  H.git(root, { "config", "user.email", "pi.nvim@example.invalid" })
  H.write(root .. "/tracked.txt", "base\n")
  H.git(root, { "add", "tracked.txt" })
  H.git(root, { "commit", "-qm", "base" })
  H.write(sibling .. "/file", "untouched\n")
  local git = assert(Git.new(root))
  local tree = assert(git:snapshot())
  local real_index_before = real_index_tree(root)
  local ok, err = git:restore_path(tree, "../repository-evil/file")
  H.eq(nil, ok)
  H.eq("git", err.kind)
  H.eq("untouched\n", H.read(sibling .. "/file"))
  assert_real_index(root, real_index_before, "rejected path")
  git:cleanup()
end)
